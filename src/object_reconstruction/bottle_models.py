"""
Data models for Object-Specific 3D Reconstruction (Phase 5.5).
Defines profile samples, reconstruction parameters, 3D mesh container, and silhouette metrics.
"""

from dataclasses import dataclass, field, asdict
from pathlib import Path
from typing import Dict, List, Optional, Tuple, Union
import numpy as np


@dataclass
class BottleProfileSample:
    """A single discrete axial cross-section of the surface of revolution."""
    z_axial: float           # Coordinate along bottle longitudinal axis (0 = base, H = cap top)
    radius: float            # Cross-sectional radius at z_axial (must be > 0)
    region: str              # Section name: "base", "body", "shoulder", "neck", "cap"

    def to_dict(self) -> dict:
        return asdict(self)


@dataclass
class BottleParameters:
    """
    Parametric specification of the bottle geometry.
    Strictly differentiates between estimated (data-constrained) and assumed (prior-driven) parameters.
    """
    # 1. Estimated / Data-Constrained Parameters
    cap_center_world: List[float]       # [X, Y, Z] in SfM world coordinates (from cap points centroid)
    total_height: float                 # Longitudinal height H in arbitrary SfM units
    body_radius: float                  # Main body radius R_body in arbitrary SfM units
    axis_tilt_x_deg: float              # Angular deviation of axis from world UP vector around X
    axis_tilt_z_deg: float              # Angular deviation of axis from world UP vector around Z
    
    # 2. Assumed / Prior-Driven Architectural Parameters
    shoulder_z_ratio: float = 0.65      # Normalized z where shoulder starts (transition from body)
    neck_z_ratio: float = 0.82          # Normalized z where neck starts (end of shoulder taper)
    cap_z_ratio: float = 0.90           # Normalized z where cap starts
    neck_radius_ratio: float = 0.38     # R_neck / R_body
    cap_radius_ratio: float = 0.42      # R_cap / R_body
    base_radius_ratio: float = 0.95     # R_base / R_body (slight taper at bottom)
    base_chamfer_z_ratio: float = 0.05  # Normalized z for base rounding
    
    # 3. Discretization Parameters
    axial_resolution: int = 60          # Number of axial profile rings
    angular_resolution: int = 36        # Number of radial samples per ring

    def to_dict(self) -> dict:
        return asdict(self)


@dataclass
class SilhouetteViewMetric:
    """Quantitative silhouette projection agreement metrics for a single camera view."""
    camera_id: int
    image_name: str
    is_train_split: bool
    intersection_px: int
    union_px: int
    iou: float
    precision: float                    # intersection / rendered_mask_px
    recall: float                       # intersection / observed_mask_px
    observed_mask_px: int
    rendered_mask_px: int

    def to_dict(self) -> dict:
        return asdict(self)


class Mesh3D:
    """
    Lightweight, self-contained 3D triangular mesh container.
    Provides vertex and face normal computation, PLY and OBJ exporters.
    """

    def __init__(
        self,
        vertices: np.ndarray,
        faces: np.ndarray,
        normals: Optional[np.ndarray] = None,
    ):
        self.vertices = np.asarray(vertices, dtype=np.float64)
        self.faces = np.asarray(faces, dtype=np.int32)
        if normals is not None:
            self.normals = np.asarray(normals, dtype=np.float64)
        else:
            self.normals = self.compute_vertex_normals()

    @property
    def num_vertices(self) -> int:
        return len(self.vertices)

    @property
    def num_faces(self) -> int:
        return len(self.faces)

    def compute_face_normals(self) -> np.ndarray:
        """Computes unnormalized or unit normal vectors for each triangular face."""
        v0 = self.vertices[self.faces[:, 0]]
        v1 = self.vertices[self.faces[:, 1]]
        v2 = self.vertices[self.faces[:, 2]]
        cross = np.cross(v1 - v0, v2 - v0)
        norm = np.linalg.norm(cross, axis=1, keepdims=True)
        norm[norm == 0] = 1.0
        return cross / norm

    def compute_vertex_normals(self) -> np.ndarray:
        """Computes area-weighted vertex normals by accumulating adjacent face normals."""
        v_normals = np.zeros_like(self.vertices)
        f_normals = self.compute_face_normals()
        for idx in range(3):
            np.add.at(v_normals, self.faces[:, idx], f_normals)
        norm = np.linalg.norm(v_normals, axis=1, keepdims=True)
        norm[norm == 0] = 1.0
        return v_normals / norm

    def export_obj(self, filepath: Union[str, Path]) -> Path:
        """Exports mesh to standard Wavefront OBJ format."""
        path = Path(filepath)
        path.parent.mkdir(parents=True, exist_ok=True)
        with open(path, "w", encoding="utf-8") as f:
            f.write("# Wavefront OBJ generated by 3DCV Project (Phase 5.5)\n")
            f.write(f"# Vertices: {self.num_vertices}, Faces: {self.num_faces}\n")
            for v in self.vertices:
                f.write(f"v {v[0]:.6f} {v[1]:.6f} {v[2]:.6f}\n")
            for vn in self.normals:
                f.write(f"vn {vn[0]:.6f} {vn[1]:.6f} {vn[2]:.6f}\n")
            for face in self.faces:
                # 1-indexed in OBJ
                f.write(f"f {face[0]+1}//{face[0]+1} {face[1]+1}//{face[1]+1} {face[2]+1}//{face[2]+1}\n")
        return path

    def export_ply(self, filepath: Union[str, Path]) -> Path:
        """Exports mesh to ASCII Stanford PLY format."""
        path = Path(filepath)
        path.parent.mkdir(parents=True, exist_ok=True)
        with open(path, "w", encoding="utf-8") as f:
            f.write("ply\n")
            f.write("format ascii 1.0\n")
            f.write("comment Created by 3DCV Project Phase 5.5 Parametric Bottle Reconstruction\n")
            f.write(f"element vertex {self.num_vertices}\n")
            f.write("property float x\n")
            f.write("property float y\n")
            f.write("property float z\n")
            f.write("property float nx\n")
            f.write("property float ny\n")
            f.write("property float nz\n")
            f.write(f"element face {self.num_faces}\n")
            f.write("property list uchar int vertex_indices\n")
            f.write("end_header\n")
            for v, vn in zip(self.vertices, self.normals):
                f.write(f"{v[0]:.6f} {v[1]:.6f} {v[2]:.6f} {vn[0]:.6f} {vn[1]:.6f} {vn[2]:.6f}\n")
            for face in self.faces:
                f.write(f"3 {face[0]} {face[1]} {face[2]}\n")
        return path

